#include <stdio.h>
#include <locale.h>
#include <malloc.h>
#include "p_function.h"

#define L_DIAPAZON_MASSIV 1
#define R_DIAPAZON_MASSIV 99

int main(){
    setlocale(0,"");
    setlocale(LC_NUMERIC, "C");

    FILE* out_file = fopen("output.txt", "a");
    fprintf(out_file, "\nПрограмма 4.2v24. Сборка: %s %s", __DATE__, __TIME__);
    fprintf(out_file, "\n--------------------------------------------------------------------------\n");
//vvod
    int m = input('m', L_DIAPAZON_MASSIV, R_DIAPAZON_MASSIV);
    int n = input('n', L_DIAPAZON_MASSIV, R_DIAPAZON_MASSIV);

    FILE* in_file = fopen("input.txt", "r");
    double** A;
    mass_input(in_file, &A, m, n);
    fclose(in_file);
//vvedeno

    mass_print(out_file, 'A', A, m, n);

//obrabotka
    int flag = 0;
    int id_max = find_id_max(A, m, n, &flag);

//otvet
    fprintf(out_file, "\n\n==========================================================================\n\n\t\t");
    fprintf(out_file, "Результат:\n\n");

    if (flag){
        fprintf(out_file, "Номер столбца с максимальным средним отрицательных элементов: %d", id_max);
    }else fprintf(out_file, "Отрицательных элементов в массиве нет");

    fprintf(out_file, "\n\n==========================================================================\n\n\n");


    mass_free(&A, m);
    fclose(out_file);
    return 0;
}
